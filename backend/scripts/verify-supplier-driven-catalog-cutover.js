"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "../..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");

const routes = read("backend/config/storefrontRouteContract.js");
const server = read("backend/server.js");
const detail = read("frontend/js/product-detail.js");
const product = read("frontend/product.html");
const catalog = read("backend/services/catalogService.js");
const publication = read("backend/services/packageMarketPublicationService.js");
const routing = read("backend/config/fulfillmentRoutingMode.js");
const fazer = read("backend/services/suppliers/fazercardsFulfillmentProcessor.js");
const wondd = read("backend/services/suppliers/wonddFulfillmentProcessor.js");
const ingestion = read("backend/services/supplierCatalog/providers/wonddCatalogIngestionService.js");
const reset = read("backend/scripts/catalog-cutover-reset.js");

for (const page of ["mlbb.html","pubg.html","pubg-rp.html","freefire.html","hok.html","aov-id.html","genshin.html","roblox.html","telegram.html"]) assert(!routes.includes(`\"${page}\", \"product\"`), `${page} cannot be a renderer`);
assert(server.includes('const renderer = PRODUCT_RENDERERS[productCode] || "product.html"'), "generic product renderer remains the server authority");
assert(!product.includes("canonical-game-input-contracts"), "generic product cannot load game input fallback");
assert(!detail.includes("AZIEL_GAME_INPUT_CONTRACTS") && !detail.includes("PRODUCT_COPY"), "generic product uses catalog data only");
assert(catalog.includes('env.CATALOG_SOURCE || "database"') && catalog.includes('env.STORE_CATALOG_SELECTION_MODE || "EXPLICIT"'), "database and Store Catalog are default authorities");
assert(publication.includes("pkg.publication?.published === true"), "Package Selling gates public packages");
assert(routing.includes("return FULFILLMENT_ROUTING_MODES.SELECTED"), "new checkout defaults to selected route authority");
assert(!fazer.includes("SUPPORTED_PRODUCT_CATEGORIES") && !fazer.includes("buildFazerCardsFields("), "FazerCards new orders require declarative contracts");
assert(!wondd.includes("wonddCatalogConfig") && !wondd.includes("buildWonddGameId("), "WonDD execution is contract-driven");
assert(!ingestion.includes("WONDD_FAMILIES") && !ingestion.includes("familyForServiceId"), "WonDD ingestion has no product-family registry requirement");
for (const guard of ["DRY_RUN", "activeIngestionLocks", "unknownHistoricalDependencies", "referencedMappingIds", "AZIEL_ALLOW_CATALOG_CUTOVER_RESET"]) assert(reset.includes(guard), `reset guard missing: ${guard}`);
console.log("Supplier-driven catalog cutover verifier: PASS");
