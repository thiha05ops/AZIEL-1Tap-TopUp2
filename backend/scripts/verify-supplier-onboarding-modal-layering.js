"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "../..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const wizard = read("frontend/js/admin-add-product-wizard.js");
const reconciliation = read("frontend/js/admin-supplier-catalog.js");
const css = read("frontend/css/admin/admin-supplier-catalog.css");
const components = read("frontend/css/admin-v2/components.css");
let checks = 0;
const ok = (value, message) => { assert.ok(value, message); checks += 1; };
ok(/business-wizard-modal[\s\S]{0,160}z-index:\s*1400/.test(components), "wizard tier remains 1400");
ok(/supplier-reconciliation-modal\{z-index:1500\}/.test(css), "nested reconciliation tier above wizard");
ok(reconciliation.includes("supplierReconciliationReturnFocus"), "originating trigger retained");
ok(reconciliation.includes("trigger?.focus?.()"), "focus restored on close");
ok(reconciliation.includes('event.key==="Escape"') && reconciliation.includes("closeSupplierReconciliationReview()"), "Escape closes reconciliation");
ok(reconciliation.includes('event.key==="Tab"') && reconciliation.includes("focusable"), "nested dialog traps tab focus");
ok(wizard.includes('document.getElementById("supplierReconciliationModal")?.hidden!==false'), "underlying wizard ignores backdrop and Escape while nested dialog is open");
ok(wizard.includes("openSupplierReconciliationReview(review.dataset.onboardReview,review)"), "review trigger is passed for restoration");
ok(!wizard.includes("Step 6") && !wizard.includes("step===6"), "five-step flow retained");
console.log(JSON.stringify({ result: "PASS", checks, wizardZIndex: 1400, reconciliationZIndex: 1500, focusRestore: true, focusTrap: true, escapeOwnership: true, wizardStatePreserved: true }, null, 2));
