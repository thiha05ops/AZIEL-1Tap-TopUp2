"use strict";

const assert = require("assert");
const crypto = require("crypto");
const { createDingerApiClient, normalizePayPayload, parseDingerTokenResponse } = require("../services/dinger/dingerApiClient");

(async () => {
    const { publicKey, privateKey } = crypto.generateKeyPairSync("rsa", {
        modulusLength: 1024,
        publicKeyEncoding: { type: "spki", format: "pem" },
        privateKeyEncoding: { type: "pkcs8", format: "pem" }
    });
    const calls = [];
    const fetchImpl = async (url, init) => {
        calls.push({ url: String(url), init });
        if (calls.length === 1) return { ok: true, status: 200, text: async () => '{"code":"000","message":"Authentication Success","time":"20260923 140635","response":{"paymentToken":"TOKEN","expireIn":"20260923 142135"}}' };
        return { ok: true, status: 200, text: async () => '{"code":"000","response":{"formToken":"FORM"}}' };
    };
    const client = createDingerApiClient({
        configuration: { enabled: true, baseUrl: "https://staging.dinger.asia/payment-gateway-uat/", projectName: "project", apiKey: "secret", merchantName: "merchant", publicKey, tokenTimestampUtcOffsetMinutes: 390, tokenTimeoutMs: 1000, payTimeoutMs: 1000 },
        fetchImpl,
        clock: () => new Date("2026-09-23T07:00:00.000Z"),
        parsePayResponse: parsed => parsed
    });
    const result = await client.createPayment({ providerName: "Wave Pay", methodName: "PIN", totalAmount: 500, orderId: "ATT-1", customerPhone: "0912345678", customerName: "Test Customer", items: [{ name: "Item" }], currency: "MMK" });
    assert.strictEqual(result.code, "000");
    assert.strictEqual(calls[1].url, "https://staging.dinger.asia/payment-gateway-uat/api/pay");
    assert.strictEqual(calls[1].init.method, "POST");
    assert.strictEqual(calls[1].init.headers.Authorization, "Bearer TOKEN");
    assert.strictEqual(calls[1].init.headers["Content-Type"], undefined, "multipart boundary must be generated by FormData");
    assert(calls[1].init.body instanceof FormData);
    const ciphertext = calls[1].init.body.get("payload");
    assert.strictEqual(typeof ciphertext, "string");
    assert.deepStrictEqual([...calls[1].init.body.keys()], ["payload"]);
    const encryptedBytes = Buffer.from(ciphertext, "base64");
    const decryptedBlocks = [];
    for (let offset = 0; offset < encryptedBytes.length; offset += 128) {
        decryptedBlocks.push(crypto.privateDecrypt({ key: privateKey, padding: crypto.constants.RSA_PKCS1_PADDING }, encryptedBytes.subarray(offset, offset + 128)));
    }
    const decrypted = JSON.parse(Buffer.concat(decryptedBlocks).toString("utf8"));
    assert.deepStrictEqual(decrypted, { providerName: "Wave Pay", methodName: "PIN", totalAmount: 500, orderId: "ATT-1", customerPhone: "0912345678", customerName: "Test Customer", items: '[{"name":"Item"}]', currency: "MMK" });

    const responseContext = { httpStatus: 200, bodyNonempty: true, jsonParsed: true, tokenTimestampUtcOffsetMinutes: 390, nowMs: Date.parse("2026-09-23T07:00:00.000Z") };
    const token = parseDingerTokenResponse({ code: "000", message: "Authentication Success", time: "20260923 140635", response: { paymentToken: "TOKEN-2", expireIn: "20260923 142135" } }, responseContext);
    assert.strictEqual(token.paymentToken, "TOKEN-2");
    assert.strictEqual(token.expireIn, "20260923 142135");
    assert.strictEqual(parseDingerTokenResponse({ code: 0, response: { paymentToken: "TOKEN-3", expireIn: "20260923 142135" } }, responseContext).paymentToken, "TOKEN-3");
    assert.throws(() => parseDingerTokenResponse({ code: "001", response: { paymentToken: "NO", expireIn: "20260923 142135" } }, responseContext), error => error.code === "DINGER_TOKEN_REJECTED");
    assert.throws(() => parseDingerTokenResponse({ code: "000", response: { expireIn: "20260923 142135" } }, responseContext), error => error.code === "DINGER_TOKEN_RESPONSE_INVALID");
    assert.throws(() => parseDingerTokenResponse({ code: "000", response: { paymentToken: "TOKEN", expireIn: "20260230 000000" } }, responseContext), error => error.code === "DINGER_RESPONSE_INVALID");
    assert.throws(() => parseDingerTokenResponse({ code: "000", response: { paymentToken: "TOKEN", expireIn: "20260923 130000" } }, responseContext), error => error.code === "DINGER_RESPONSE_INVALID" && error.failureCategory === "EXPIRY_INVALID");
    assert.throws(() => parseDingerTokenResponse({ code: "000", token: { paymentToken: "LEGACY", expiredAt: "20260923 142135" } }, responseContext), error => error.code === "DINGER_TOKEN_RESPONSE_INVALID", "unverified legacy nesting must remain rejected");

    assert.throws(() => normalizePayPayload({ providerName: "Wave Pay", methodName: "PIN", totalAmount: 499, orderId: "A", customerPhone: "09", customerName: "T", items: [] }), error => error.code === "DINGER_PAYLOAD_INVALID");
    assert.throws(() => normalizePayPayload({ providerName: "Wave Pay", methodName: "PIN", totalAmount: 500.5, orderId: "A", customerPhone: "09", customerName: "T", items: [] }), error => error.code === "DINGER_PAYLOAD_INVALID");
    assert.throws(() => normalizePayPayload({ providerName: "Wave Pay", methodName: "PIN", totalAmount: 500, orderId: "A".repeat(51), customerPhone: "09", customerName: "T", items: [] }), error => error.code === "DINGER_PAYLOAD_INVALID");
    assert.throws(() => normalizePayPayload({ providerName: "Wave Pay", methodName: "PIN", totalAmount: 500, orderId: "A", customerPhone: "", customerName: "T", items: [] }), error => error.code === "DINGER_PAYLOAD_INVALID");

    console.log("Dinger Pay API request construction verification passed.");
})().catch(error => { console.error(error); process.exit(1); });
